export const DEFAULT_THEME_ID = "forest";
export const THEME_SETTING_KEY = "siteTheme";

/** البحث عن لوحة بالمعرّف (مع رجوع لللوحة الافتراضية) */
export function findTheme(id: string | null | undefined): SiteTheme {
  return THEMES.find((t) => t.id === id) ?? THEMES.find((t) => t.id === DEFAULT_THEME_ID)!;
}

/** تحويل اللوحة إلى نص CSS جاهز للحقن في :root */
export function themeCssText(theme: SiteTheme): string {
  return Object.entries(theme.vars)
    .map(([k, v]) => `${k}:${v};`)
    .join("");
}

/** خريطة {معرّف اللوحة: نص CSS} للتطبيق الفوري من جهة العميل */
export function themeCssMap(): Record<string, string> {
  const map: Record<string, string> = {};
  for (const t of THEMES) map[t.id] = themeCssText(t);
  return map;
}
